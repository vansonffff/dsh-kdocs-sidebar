#!/usr/bin/env node
/**
 * Build `client.pdf.js`: the lazily loaded PDF-preview chunk.
 *
 * The chunk is a classic script, like `client.js` itself: no bundler exists in
 * this profile, so this script concatenates the vendored pdf.js UMD (wrapped so
 * its CommonJS branch lands in a private module object instead of clobbering the
 * chunk's own exports) with the viewer source, and wraps both in the module
 * loader's chunk registration — the exact shape the product's own
 * documentpreview uses for its `client.pdf.js`.
 *
 * Run `node scripts/build-pdf-chunk.mjs` after editing
 * `src/client/pdf-viewer.js` or bumping `vendor/pdfjs-*.min.js`.
 * `--check` verifies the committed chunk is in sync without writing.
 *
 * @module kdocs/scripts/build-pdf-chunk
 */

import { readFileSync, writeFileSync } from 'node:fs';

const VENDOR = new URL('../vendor/pdfjs-3.11.174.min.js', import.meta.url);
const WORKER = new URL('../vendor/pdfjs-worker-3.11.174.min.js', import.meta.url);
const VIEWER = new URL('../src/client/pdf-viewer.js', import.meta.url);
const OUTPUT = new URL('../client.pdf.js', import.meta.url);

const vendor = readFileSync(VENDOR, 'utf8');
// The worker ships as a string and becomes a blob: URL at runtime: pdf.js v3
// refuses to run without a `workerSrc`, and the classic-script runtime has no
// static file URL to hand it — a blob is the offline answer.
const worker = JSON.stringify(readFileSync(WORKER, 'utf8'));
const viewer = readFileSync(VIEWER, 'utf8')
  // The viewer source is written as an ES module for lintability; the chunk
  // needs the function body, so the export wrapper comes off here.
  .replace(/^export function createPdfViewer/m, 'function createPdfViewer');

const output = `/**
 * GENERATED by scripts/build-pdf-chunk.mjs — do not edit.
 *
 * The desktop shell's PDF preview chunk: vendored pdf.js (Apache-2.0, see
 * vendor/pdfjs-LICENSE.txt) plus the viewer from src/client/pdf-viewer.js.
 * Loaded lazily via require.async('./client.pdf.js') the first time a desktop
 * preview opens; the web profile never downloads it.
 */

window.__ModuleLoader__.load({
  id: 'dsh-kdocs-inside',
  chunk: 'client.pdf.js',
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;

    const react = require('react');
    const jsxRuntime = require('react/jsx-runtime');

    // The vendored UMD prefers a CommonJS branch when module/exports exist. It
    // gets a PRIVATE pair: the chunk's own exports belong to the viewer.
    const pdfjsModule = { exports: {} };
    (function (module, exports, self, window, document) {
${vendor}
    }).call(undefined, pdfjsModule, pdfjsModule.exports, window, window, document);
    const pdfjsLib = pdfjsModule.exports;

    // No static worker URL exists in this runtime, so the worker source rides
    // the chunk as a string and becomes a blob: URL — pdf.js v3 refuses to run
    // with no workerSrc at all (measured: "No GlobalWorkerOptions.workerSrc
    // specified" and zero pages).
    pdfjsLib.GlobalWorkerOptions.workerSrc = URL.createObjectURL(new Blob([${worker}], { type: 'text/javascript' }));

${viewer}

    exports.KDocsPdfViewer = createPdfViewer(react, jsxRuntime, pdfjsLib);
    return module.exports;
  },
});
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== output) {
    console.error('client.pdf.js is out of sync — run: node scripts/build-pdf-chunk.mjs');
    process.exit(1);
  }
  console.log('client.pdf.js is in sync');
} else {
  writeFileSync(OUTPUT, output);
  console.log(`wrote client.pdf.js (${(output.length / 1024).toFixed(0)} KB)`);
}
